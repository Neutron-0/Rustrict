use std::collections::HashMap;
use std::net::Ipv4Addr;
use serde::Serialize;

use crate::core::assessment::{AuditFinding, AuditSeverity, ServiceEntry};
use crate::core::scope::ScopeManager;

#[derive(Serialize)]
pub struct JsonAssessmentReport<'a> {
    pub tool: &'static str,
    pub version: &'static str,
    pub scope: &'a ScopeManager,
    pub services: &'a HashMap<Ipv4Addr, Vec<ServiceEntry>>,
    pub findings: &'a [AuditFinding],
}

/// Generates an executive assessment summary in Markdown format.
pub fn export_markdown(
    scope: &ScopeManager,
    services: &HashMap<Ipv4Addr, Vec<ServiceEntry>>,
    findings: &[AuditFinding],
) -> String {
    let mut out = String::new();

    out.push_str("# Rustrict Active Posture & Assessment Report\n\n");
    out.push_str("> Generated by Rustrict - High-Performance Security & Resilience Platform\n\n");

    // Scope Details
    out.push_str("## 1. Scope & Boundaries\n\n");
    out.push_str(&format!("- **Strict Enforcement Mode:** {}\n", if scope.strict_mode { "ENABLED" } else { "DISABLED" }));
    if scope.allowed_cidrs.is_empty() {
        out.push_str("- **Allowed CIDRs:** *None configured (All IPv4 allowed when strict mode is off)*\n");
    } else {
        let cidrs: Vec<String> = scope.allowed_cidrs.iter().map(|c| c.to_string()).collect();
        out.push_str(&format!("- **Allowed CIDRs:** {}\n", cidrs.join(", ")));
    }
    out.push_str(&format!("- **Excluded Hosts (IP):** {}\n", scope.excluded_ips.len()));
    out.push_str(&format!("- **Excluded Adapters (MAC):** {}\n\n", scope.excluded_macs.len()));

    // Executive Metrics
    let mut crit = 0;
    let mut high = 0;
    let mut med = 0;
    let mut low = 0;
    let mut info = 0;

    for f in findings {
        match f.severity {
            AuditSeverity::Critical => crit += 1,
            AuditSeverity::High => high += 1,
            AuditSeverity::Medium => med += 1,
            AuditSeverity::Low => low += 1,
            AuditSeverity::Info => info += 1,
        }
    }

    out.push_str("## 2. Assessment Summary & Metrics\n\n");
    out.push_str("| Metric | Value |\n");
    out.push_str("| --- | --- |\n");
    out.push_str(&format!("| Hosts with Open Services | {} |\n", services.len()));
    let total_services: usize = services.values().map(|v| v.len()).sum();
    out.push_str(&format!("| Total Discovered Services | {} |\n", total_services));
    out.push_str(&format!("| Total Security Findings | {} |\n", findings.len()));
    out.push_str(&format!("| Critical Vulnerabilities | {} |\n", crit));
    out.push_str(&format!("| High Risk Issues | {} |\n", high));
    out.push_str(&format!("| Medium Risk Issues | {} |\n", med));
    out.push_str(&format!("| Low Risk / Informational | {} |\n\n", low + info));

    // Discovered Services Table
    out.push_str("## 3. Discovered Network Services\n\n");
    if services.is_empty() {
        out.push_str("*No active services discovered or port scan not run.*\n\n");
    } else {
        out.push_str("| Target Host | Port | Proto | Service | Banner / Version |\n");
        out.push_str("| --- | --- | --- | --- | --- |\n");
        let mut sorted_ips: Vec<&Ipv4Addr> = services.keys().collect();
        sorted_ips.sort();

        for ip in sorted_ips {
            if let Some(entries) = services.get(ip) {
                for s in entries {
                    let banner = s.banner.as_deref().unwrap_or("-");
                    let clean_banner = banner.replace('|', "\\|").replace('\n', " ").replace('\r', "");
                    out.push_str(&format!(
                        "| `{}` | `{}` | {} | {} | {} |\n",
                        ip, s.port, s.transport.to_uppercase(), s.service_name, clean_banner
                    ));
                }
            }
        }
        out.push('\n');
    }


    // Security Posture Findings
    out.push_str("## 4. Security Posture & Exposure Findings\n\n");
    if findings.is_empty() {
        out.push_str("*No audit findings or protocol posture tests performed.*\n\n");
    } else {
        out.push_str("| Severity | Rule ID | Target | Title | Remediation |\n");
        out.push_str("| --- | --- | --- | --- | --- |\n");
        for f in findings {
            let port_str = f.port.map(|p| format!(":{}", p)).unwrap_or_default();
            out.push_str(&format!(
                "| **{:?}** | `{}` | `{}`{port_str} | {} | {} |\n",
                f.severity, f.rule_id, f.target_ip, f.title, f.remediation
            ));
        }
        out.push_str("\n### Detailed Findings\n\n");
        for (idx, f) in findings.iter().enumerate() {
            let port_str = f.port.map(|p| format!(":{}", p)).unwrap_or_default();
            out.push_str(&format!(
                "#### {}. [{:?}] {} (`{}`{})\n\n",
                idx + 1, f.severity, f.title, f.target_ip, port_str
            ));
            out.push_str(&format!("- **Rule ID:** `{}`\n", f.rule_id));
            out.push_str(&format!("- **Description:** {}\n", f.description));
            out.push_str(&format!("- **Recommended Remediation:** {}\n\n", f.remediation));
        }
    }

    out
}

/// Generates a structured JSON asset inventory and findings report.
pub fn export_json(
    scope: &ScopeManager,
    services: &HashMap<Ipv4Addr, Vec<ServiceEntry>>,
    findings: &[AuditFinding],
) -> Result<String, serde_json::Error> {
    let report = JsonAssessmentReport {
        tool: "Rustrict",
        version: "2.0.0",
        scope,
        services,
        findings,
    };
    serde_json::to_string_pretty(&report)
}

/// Generates a SARIF v2.1.0 report for findings.
pub fn export_sarif(findings: &[AuditFinding]) -> Result<String, serde_json::Error> {
    use serde_json::json;

    let mut rules = Vec::new();
    let mut seen_rules = std::collections::HashSet::new();

    for f in findings {
        if seen_rules.insert(f.rule_id.clone()) {
            let level = match f.severity {
                AuditSeverity::Critical | AuditSeverity::High => "error",
                AuditSeverity::Medium => "warning",
                AuditSeverity::Low | AuditSeverity::Info => "note",
            };

            rules.push(json!({
                "id": f.rule_id,
                "name": f.title,
                "shortDescription": { "text": f.title },
                "fullDescription": { "text": f.description },
                "defaultConfiguration": {
                    "level": level
                },
                "help": {
                    "text": format!("Remediation: {}", f.remediation)
                }
            }));
        }
    }

    let results: Vec<_> = findings.iter().map(|f| {
        let level = match f.severity {
            AuditSeverity::Critical | AuditSeverity::High => "error",
            AuditSeverity::Medium => "warning",
            AuditSeverity::Low | AuditSeverity::Info => "note",
        };

        let target_endpoint = if let Some(p) = f.port {
            format!("{}:{}", f.target_ip, p)
        } else {
            f.target_ip.to_string()
        };

        json!({
            "ruleId": f.rule_id,
            "level": level,
            "message": {
                "text": format!("{}: {}", f.title, f.description)
            },
            "locations": [
                {
                    "logicalLocations": [
                        {
                            "name": target_endpoint,
                            "kind": "network-endpoint"
                        }
                    ]
                }
            ]
        })
    }).collect();

    let sarif = json!({
        "$schema": "https://raw.githubusercontent.com/oasis-tcs/sarif-spec/master/Schemata/sarif-schema-2.1.0.json",
        "version": "2.1.0",
        "runs": [
            {
                "tool": {
                    "driver": {
                        "name": "Rustrict",
                        "version": "2.0.0",
                        "informationUri": "https://github.com/Neutron-0/Rustrict",
                        "rules": rules
                    }
                },
                "results": results
            }
        ]
    });

    serde_json::to_string_pretty(&sarif)
}

/// Helper function to save exported report to disk.
pub fn save_report(path: &str, content: &str) -> std::io::Result<()> {
    std::fs::write(path, content)
}
